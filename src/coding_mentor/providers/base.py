"""Base definitions and protocols for LLM providers."""

from __future__ import annotations

import json
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any, Optional

if TYPE_CHECKING:
    from coding_mentor.config import MentorConfig


class ProviderError(Exception):
    """Base exception for LLM provider communication or format failures."""


@dataclass
class ChatMessage:
    """Represents a single message in a chat history."""

    role: str  # 'system', 'user', 'assistant', 'tool'
    content: str
    name: Optional[str] = None
    tool_call_id: Optional[str] = None

    def to_dict(self) -> dict[str, Any]:
        """Convert to standard API payload dictionary."""
        d: dict[str, Any] = {"role": self.role, "content": self.content}
        if self.name:
            d["name"] = self.name
        if self.tool_call_id:
            d["tool_call_id"] = self.tool_call_id
        return d


@dataclass
class ToolCall:
    """Represents an agentic tool call generated by the model."""

    id: str
    name: str
    arguments: dict[str, Any] = field(default_factory=dict)

    @classmethod
    def from_raw(cls, call_id: str, name: str, args_raw: str | dict[str, Any]) -> ToolCall:
        """Parse raw arguments safely into a dictionary."""
        if isinstance(args_raw, dict):
            return cls(id=call_id, name=name, arguments=args_raw)
        try:
            parsed = json.loads(args_raw) if args_raw else {}
            if not isinstance(parsed, dict):
                parsed = {"raw": parsed}
        except Exception:
            parsed = {"raw": args_raw}
        return cls(id=call_id, name=name, arguments=parsed)


@dataclass
class LLMResponse:
    """Standardized response from an LLM provider."""

    content: str
    tool_calls: list[ToolCall] = field(default_factory=list)
    model: str = ""
    usage: dict[str, int] = field(default_factory=dict)

    @property
    def has_tool_calls(self) -> bool:
        """Return True if model requested one or more tool calls."""
        return len(self.tool_calls) > 0


class LLMProvider(ABC):
    """Abstract interface defining the contract for model providers."""

    @abstractmethod
    def generate(
        self,
        messages: list[ChatMessage],
        tools: Optional[list[dict[str, Any]]] = None,
        temperature: float = 0.7,
    ) -> LLMResponse:
        """Send chat messages and optional tool schemas to the model.

        Args:
            messages: List of chat messages in the conversation.
            tools: Optional tool/function schemas.
            temperature: Sampling temperature.

        Returns:
            Standardized LLMResponse.

        Raises:
            ProviderError: If the API request or response processing fails.
        """

    @abstractmethod
    def is_available(self) -> bool:
        """Return True if the provider is properly configured and reachable."""


def get_provider(config: MentorConfig) -> LLMProvider:
    """Factory creating an LLMProvider instance based on application configuration."""
    from coding_mentor.providers.mock_provider import MockProvider
    from coding_mentor.providers.openai_provider import OpenAIProvider

    provider_type = config.llm_provider.lower().strip()
    if provider_type in ("mock", "offline", "test"):
        return MockProvider(model=config.llm_model)

    if provider_type in ("openai", "openai-compatible"):
        return OpenAIProvider(
            api_key=config.api_key,
            model=config.llm_model,
            base_url=config.base_url,
        )

    raise ProviderError(
        f"Unsupported LLM provider '{config.llm_provider}'. Supported: 'openai', 'openai-compatible', 'mock'."
    )
